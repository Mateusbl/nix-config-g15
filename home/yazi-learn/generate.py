"""Build the data for `yazi-learn` from Yazi's real keymap.

Lessons (lessons.json, written by home/yazi-learn.nix) name Yazi *actions* (the `run`
strings of the keymap), never keys. This script looks every action up in

  1. this config's own additions (programs.yazi.keymap.mgr.prepend_keymap), then
  2. the installed Yazi's default keymap (yazi-config/preset/keymap-default.toml),

and writes lesson texts, flashcards, a cheatsheet and docs with the real keys.
If a lesson names an action that no key runs, the build fails.

Usage: generate.py <keymap-default.toml> <overrides.json> <lessons.json> <out-dir> <yazi-version>
"""

import json
import re
import sys
import tomllib
from pathlib import Path

default_toml, overrides_json, lessons_json, out_dir, yazi_version = sys.argv[1:6]
out = Path(out_dir)
out.mkdir(parents=True)


def key_text(on):
    return on if isinstance(on, str) else " ".join(on)


def run_text(run):
    return run if isinstance(run, str) else " ; ".join(run)


# --- The effective [mgr] keymap: additions first (they win), then the defaults. -------
defaults = tomllib.loads(Path(default_toml).read_text())["mgr"]["keymap"]
additions = json.loads(Path(overrides_json).read_text())

entries = []  # (keys, run, desc, source)
taken = set()
for e in additions:
    k = key_text(e["on"])
    entries.append((k, run_text(e["run"]), e.get("desc", ""), "this config"))
    taken.add(k)
for e in defaults:
    k = key_text(e["on"])
    if k in taken:  # shadowed by an addition (none today, but keep the logic honest)
        continue
    entries.append((k, run_text(e["run"]), e.get("desc", ""), "default"))

by_run = {}
for keys, run, desc, source in entries:
    by_run.setdefault(run, []).append((keys, desc, source))


def keys_for(run):
    found = by_run.get(run)
    if not found:
        return None
    return " / ".join(k for k, _, _ in found)


# --- Lessons --------------------------------------------------------------------------
lessons = json.loads(Path(lessons_json).read_text())
missing = []
placeholder = re.compile(r"\{\{(.+?)\}\}")


def fill(text, where):
    """Replace {{action}} with the keys for that action."""

    def sub(m):
        k = keys_for(m.group(1))
        if k is None:
            missing.append(f"{where}: {{{{{m.group(1)}}}}}")
            return "??"
        return k

    return placeholder.sub(sub, text)


rendered = []
cards = []
for n, lesson in enumerate(lessons, start=1):
    where = f"lesson {n} ({lesson['title']})"
    lines = [f"Lesson {n}: {lesson['title']}", "", "Goal: " + fill(lesson["goal"], where), ""]
    lines.append("Keys:")
    rows = []
    for step in lesson["steps"]:
        k = keys_for(step["run"])
        if k is None:
            missing.append(f"{where}: action `{step['run']}`")
            continue
        desc = step.get("note") or by_run[step["run"]][0][1]
        rows.append((k, desc))
        cards.append((n, desc, k))
    width = max((len(k) for k, _ in rows), default=0)
    lines += [f"  {k.ljust(width)}  {d}" for k, d in rows]
    lines += ["", "Try it: " + fill(lesson["try"], where)]
    for extra in lesson.get("notes", []):
        lines += ["", fill(extra, where)]
    lines += ["", "Check: " + fill(lesson["question"], where)]
    answer = fill(lesson["answer"], where)
    rendered.append((n, lesson["title"], "\n".join(lines), answer, rows, lesson))

if missing:
    print("yazi-learn: these lessons reference keys/actions that do not exist in", file=sys.stderr)
    print(f"Yazi {yazi_version}'s keymap (defaults + this config):", file=sys.stderr)
    for m in missing:
        print("  - " + m, file=sys.stderr)
    sys.exit(1)

for n, title, text, answer, _, _ in rendered:
    (out / f"lesson-{n:02d}.txt").write_text(text + "\n")
    (out / f"answer-{n:02d}.txt").write_text(answer + "\n")
(out / "titles.tsv").write_text("".join(f"{n}\t{t}\n" for n, t, *_ in rendered))
(out / "cards.tsv").write_text("".join(f"{n}\t{d}\t{k}\n" for n, d, k in cards))

# --- Cheatsheet: every [mgr] key, in Yazi's own order, additions marked. ----------------
width = max(len(k) for k, *_ in entries)
cheat = [f"Yazi {yazi_version} keys (manager). Open Yazi's live help with: {keys_for('help')}", ""]
for keys, run, desc, source in entries:
    mark = "  [this config]" if source == "this config" else ""
    cheat.append(f"{keys.ljust(width)}  {desc or run}{mark}")
(out / "cheat.txt").write_text("\n".join(cheat) + "\n")

# --- Markdown for docs/yazi-lessons.md ---------------------------------------------------
md = [
    "<!-- Generated by home/yazi-learn/generate.py from Yazi's keymap; do not edit by hand. -->",
    f"Generated from Yazi **{yazi_version}**'s default keymap plus this config's additions.",
    f"Yazi's live help (every key): **{keys_for('help')}**.",
    "",
]
for n, title, _, answer, rows, lesson in rendered:
    md += [f"### {n}. {title}", "", fill(lesson["goal"], ""), "", "| Keys | Does |", "| --- | --- |"]
    md += [f"| `{k}` | {d} |" for k, d in rows]
    md += ["", "Try it: " + fill(lesson["try"], "")]
    for extra in lesson.get("notes", []):
        md += ["", fill(extra, "")]
    md += ["", f"Check: {fill(lesson['question'], '')}", ""]
md += ["### All keys", "", "| Keys | Does | From |", "| --- | --- | --- |"]
md += [f"| `{k.replace('|', '\\|')}` | {(d or r).replace('|', '\\|')} | {s} |" for k, r, d, s in entries]
(out / "lessons.md").write_text("\n".join(md) + "\n")
print(f"yazi-learn: {len(rendered)} lessons, {len(cards)} cards, {len(entries)} keys")
